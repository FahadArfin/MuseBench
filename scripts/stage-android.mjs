import {readFile,mkdir,copyFile} from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {stageRelease} from './release-assets.mjs';
const pkg=JSON.parse(await readFile('package.json','utf8'));
const directory='mobile/android/app/build/outputs/apk/release';
const metadata=JSON.parse(await readFile(path.join(directory,'output-metadata.json'),'utf8'));
const build=metadata.elements?.[0];
if(metadata.applicationId!=='io.github.fahadarfin.musebench'||metadata.elements.length!==1||build.versionName!==pkg.version||build.versionCode!==Number(pkg.version.split('.')[2]))throw Error('Android release identity does not match the source version.');
if(!/^[\w.-]+\.apk$/.test(build.outputFile))throw Error('Invalid APK path.');
const apk=path.join(directory,build.outputFile);
const signer=path.join(process.env.ANDROID_HOME||process.env.ANDROID_SDK_ROOT||'', 'build-tools','35.0.0','apksigner');
const result=execFileSync(signer,['verify','--verbose','--print-certs',apk],{encoding:'utf8'});
const expected=(await readFile('mobile/android/signing-certificate.sha256','utf8')).trim();
const actual=/Signer #1 certificate SHA-256 digest: ([a-f0-9]{64})/i.exec(result)?.[1]?.toLowerCase();
if(!/^[a-f0-9]{64}$/.test(expected)||actual!==expected)throw Error('Android signing certificate does not match the stable release identity.');
await mkdir('release',{recursive:true});
await copyFile(apk,`release/MuseBench-${pkg.version}-android.apk`);
await stageRelease({releaseDir:'release',outDir:'release-assets',platform:'android',arch:'universal',version:pkg.version,commit:pkg.releaseCommit});
console.log(`Verified signed Android APK ${pkg.version}; certificate ${actual}.`);
